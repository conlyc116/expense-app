const ZH = {}; const EN = {};
for (const [k, zh, en] of TABLE) { ZH[k] = zh; EN[k] = en; }
export const DICT = { 'zh-Hant': ZH, en: EN };

const fill = (s, p) => s.replace(/\{(\w+)\}/g, (m, k) => (p && p[k] !== undefined && p[k] !== null ? String(p[k]) : m));

let current = 'zh-Hant';
const listeners = [];
export const getLang = () => current;
export function t(key, params, lang = current) {
  const d = DICT[lang] || ZH;
  let s;
  if (params && params.n === 1 && (key + '_one') in d) s = d[key + '_one'];
  else s = key in d ? d[key] : (key in ZH ? ZH[key] : key);
  return fill(s, params);
}
export const catLabel = (code, lang = current) => (('cat.' + code) in ZH ? t('cat.' + code, null, lang) : String(code || ''));
export const payLabel = (code, lang = current) => (('pay.' + code) in ZH ? t('pay.' + code, null, lang) : String(code || ''));
export function onLangChange(fn) { listeners.push(fn); }
export function setLang(l, { persist = true } = {}) {
  if (!LANGS.includes(l)) return current;
  const changed = l !== current; current = l;
  try { if (typeof document !== 'undefined') document.documentElement.lang = l === 'en' ? 'en' : 'zh-Hant-TW'; } catch (_) { /* ignore */ }
  try { if (persist && typeof localStorage !== 'undefined') localStorage.setItem(KEY, l); } catch (_) { /* ignore */ }
  if (changed) listeners.forEach((fn) => { try { fn(l); } catch (e) { console.error(e); } });
  return current;
}
// 啟動：讀 localStorage；沒有就依瀏覽器語言（不寫入，使用者手動切換才存）
export function initLang() {
  let stored = null; try { stored = typeof localStorage !== 'undefined' ? localStorage.getItem(KEY) : null; } catch (_) { /* ignore */ }
  const nav = typeof navigator !== 'undefined' ? (navigator.languages && navigator.languages.length ? [...navigator.languages] : [navigator.language]) : [];
  return setLang(pickLang(stored, nav), { persist: false });
}
