// 第一次開啟：依瀏覽器語言挑（任何 zh* → 繁體中文；其餘 → English）
export function pickLang(stored, navLangs) {
  if (LANGS.includes(stored)) return stored;
  const list = (Array.isArray(navLangs) ? navLangs : [navLangs]).filter(Boolean);
  for (const l of list) { const s = String(l).toLowerCase(); if (s.startsWith('zh')) return 'zh-Hant'; if (s.startsWith('en')) return 'en'; }
  return list.length ? 'en' : 'zh-Hant';
}

